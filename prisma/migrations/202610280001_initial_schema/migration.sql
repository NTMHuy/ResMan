-- Initial PostgreSQL schema for ResMan.
-- Generated for review; application-specific state transitions remain enforced by NestJS transactions.

CREATE TABLE roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  description TEXT,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);
CREATE TABLE permissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(80) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  module VARCHAR(50) NOT NULL,
  description TEXT
);
CREATE TABLE role_permissions (
  role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
  permission_id BIGINT NOT NULL REFERENCES permissions(id) ON DELETE RESTRICT,
  PRIMARY KEY (role_id, permission_id)
);
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
  username VARCHAR(80) NOT NULL UNIQUE,
  email VARCHAR(255),
  password_hash VARCHAR(255) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  last_login_at TIMESTAMPTZ(6),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_uq ON users(email) WHERE email IS NOT NULL;
CREATE TABLE employees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
  employee_code VARCHAR(30) NOT NULL UNIQUE,
  full_name VARCHAR(150) NOT NULL,
  phone VARCHAR(20),
  employment_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (employment_status IN ('ACTIVE','INACTIVE')),
  hired_at DATE,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);
CREATE TABLE menu_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  description TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);
CREATE TABLE kitchen_stations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  description TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE menu_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES menu_categories(id) ON DELETE RESTRICT,
  kitchen_station_id BIGINT NOT NULL REFERENCES kitchen_stations(id) ON DELETE RESTRICT,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  description TEXT,
  price NUMERIC(14,2) NOT NULL CHECK (price >= 0),
  image_url VARCHAR(1000),
  availability_status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE'
    CHECK (availability_status IN ('AVAILABLE','MANUAL_UNAVAILABLE','AUTO_OUT_OF_STOCK')),
  availability_reason TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  CONSTRAINT menu_items_id_station_uq UNIQUE (id, kitchen_station_id)
);
CREATE INDEX menu_items_availability_category_idx ON menu_items(availability_status, category_id);
CREATE INDEX menu_items_station_idx ON menu_items(kitchen_station_id);
CREATE TABLE dining_tables (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(80) NOT NULL,
  capacity INTEGER CHECK (capacity IS NULL OR capacity > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','OCCUPIED','INACTIVE')),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);
CREATE TABLE dining_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id BIGINT NOT NULL REFERENCES dining_tables(id) ON DELETE RESTRICT,
  session_code VARCHAR(80) NOT NULL UNIQUE,
  token_hash VARCHAR(255),
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED')),
  opened_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  closed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  opened_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  closed_at TIMESTAMPTZ(6),
  CONSTRAINT dining_sessions_close_check CHECK ((status = 'OPEN' AND closed_at IS NULL) OR (status = 'CLOSED' AND closed_at IS NOT NULL))
);
CREATE UNIQUE INDEX dining_sessions_one_open_per_table_uq ON dining_sessions(table_id) WHERE status = 'OPEN';
CREATE INDEX dining_sessions_table_status_idx ON dining_sessions(table_id, status);
CREATE TABLE table_devices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dining_table_id BIGINT NOT NULL REFERENCES dining_tables(id) ON DELETE RESTRICT,
  device_code VARCHAR(100) NOT NULL UNIQUE,
  device_name VARCHAR(120) NOT NULL,
  token_hash VARCHAR(255),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','REVOKED')),
  last_seen_at TIMESTAMPTZ(6),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);
CREATE INDEX table_devices_table_status_idx ON table_devices(dining_table_id, status);
CREATE TABLE customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name VARCHAR(150) NOT NULL,
  email VARCHAR(255) UNIQUE,
  phone VARCHAR(20) UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','BLOCKED')),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  CONSTRAINT customers_contact_check CHECK (email IS NOT NULL OR phone IS NOT NULL)
);
CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code VARCHAR(40) NOT NULL UNIQUE,
  order_type VARCHAR(20) NOT NULL CHECK (order_type IN ('DINE_IN','TAKEAWAY')),
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING_CONFIRMATION'
    CHECK (status IN ('PENDING_CONFIRMATION','CONFIRMED','IN_KITCHEN','PARTIALLY_READY','READY','SERVED','COMPLETED','REJECTED','CANCELLED')),
  dining_table_id BIGINT REFERENCES dining_tables(id) ON DELETE RESTRICT,
  dining_session_id BIGINT REFERENCES dining_sessions(id) ON DELETE RESTRICT,
  customer_id BIGINT REFERENCES customers(id) ON DELETE RESTRICT,
  kitchen_station_id BIGINT NOT NULL REFERENCES kitchen_stations(id) ON DELETE RESTRICT,
  guest_count INTEGER CHECK (guest_count IS NULL OR guest_count > 0),
  created_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  confirmed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  confirmed_at TIMESTAMPTZ(6),
  dispatched_at TIMESTAMPTZ(6),
  rejection_reason TEXT,
  note TEXT,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  CONSTRAINT orders_dine_in_context_check CHECK (
    (order_type = 'DINE_IN' AND dining_table_id IS NOT NULL AND dining_session_id IS NOT NULL)
    OR (order_type = 'TAKEAWAY' AND dining_table_id IS NULL AND dining_session_id IS NULL)
  ),
  CONSTRAINT orders_id_station_uq UNIQUE (id, kitchen_station_id)
);
CREATE INDEX orders_status_created_idx ON orders(status, created_at DESC);
CREATE INDEX orders_table_created_idx ON orders(dining_table_id, created_at DESC);
CREATE INDEX orders_customer_created_idx ON orders(customer_id, created_at DESC);
CREATE TABLE order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL,
  menu_item_id BIGINT NOT NULL,
  kitchen_station_id BIGINT NOT NULL,
  item_name_snapshot VARCHAR(150) NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
  line_total NUMERIC(14,2) NOT NULL CHECK (line_total >= 0),
  note TEXT,
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING_CONFIRMATION'
    CHECK (status IN ('PENDING_CONFIRMATION','QUEUED','PREPARING','READY','SERVED','REJECTED','CANCELLED')),
  terminal_reason TEXT,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  CONSTRAINT order_items_order_station_fk FOREIGN KEY (order_id, kitchen_station_id)
    REFERENCES orders(id, kitchen_station_id) ON DELETE RESTRICT,
  CONSTRAINT order_items_menu_station_fk FOREIGN KEY (menu_item_id, kitchen_station_id)
    REFERENCES menu_items(id, kitchen_station_id) ON DELETE RESTRICT
);
CREATE INDEX order_items_order_status_idx ON order_items(order_id, status);
CREATE TABLE order_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
  from_status VARCHAR(30),
  to_status VARCHAR(30) NOT NULL,
  reason TEXT,
  actor_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  changed_at TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);
CREATE INDEX order_status_history_order_changed_idx ON order_status_history(order_id, changed_at DESC);
CREATE TABLE order_item_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_item_id BIGINT NOT NULL REFERENCES order_items(id) ON DELETE RESTRICT,
  from_status VARCHAR(30),
  to_status VARCHAR(30) NOT NULL,
  reason TEXT,
  actor_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  changed_at TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);
CREATE INDEX order_item_status_history_item_changed_idx ON order_item_status_history(order_item_id, changed_at DESC);
CREATE TABLE kitchen_tickets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE,
  kitchen_station_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED','ACTIVE','COMPLETED','CANCELLED')),
  dispatched_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  CONSTRAINT kitchen_tickets_order_station_fk FOREIGN KEY (order_id, kitchen_station_id)
    REFERENCES orders(id, kitchen_station_id) ON DELETE RESTRICT
);
CREATE INDEX kitchen_tickets_station_status_dispatched_idx ON kitchen_tickets(kitchen_station_id, status, dispatched_at);
CREATE TABLE ingredients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  unit VARCHAR(30) NOT NULL,
  low_stock_threshold NUMERIC(14,3) CHECK (low_stock_threshold IS NULL OR low_stock_threshold >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);
CREATE TABLE inventory_balances (
  ingredient_id BIGINT PRIMARY KEY REFERENCES ingredients(id) ON DELETE RESTRICT,
  quantity_on_hand NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);
CREATE TABLE stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ingredient_id BIGINT NOT NULL REFERENCES ingredients(id) ON DELETE RESTRICT,
  movement_type VARCHAR(20) NOT NULL CHECK (movement_type IN ('IN','OUT','ADJUSTMENT','WASTE')),
  quantity_delta NUMERIC(14,3) NOT NULL CHECK (quantity_delta <> 0),
  reason TEXT NOT NULL,
  reference_code VARCHAR(80),
  created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  CONSTRAINT stock_movement_sign_check CHECK (
    (movement_type = 'IN' AND quantity_delta > 0)
    OR (movement_type IN ('OUT','WASTE') AND quantity_delta < 0)
    OR movement_type = 'ADJUSTMENT'
  )
);
CREATE INDEX stock_movements_ingredient_created_idx ON stock_movements(ingredient_id, created_at DESC);
CREATE TABLE shortage_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_item_id BIGINT REFERENCES order_items(id) ON DELETE RESTRICT,
  ingredient_id BIGINT REFERENCES ingredients(id) ON DELETE RESTRICT,
  reported_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  reason TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','IN_PROGRESS','RESOLVED','CANCELLED')),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  resolved_at TIMESTAMPTZ(6),
  CONSTRAINT shortage_report_reference_check CHECK (order_item_id IS NOT NULL OR ingredient_id IS NOT NULL)
);
CREATE INDEX shortage_reports_status_created_idx ON shortage_reports(status, created_at DESC);
CREATE TABLE menu_item_ingredients (
  menu_item_id BIGINT NOT NULL REFERENCES menu_items(id) ON DELETE RESTRICT,
  ingredient_id BIGINT NOT NULL REFERENCES ingredients(id) ON DELETE RESTRICT,
  PRIMARY KEY (menu_item_id, ingredient_id)
);
CREATE TABLE daily_inventory_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ingredient_id BIGINT NOT NULL REFERENCES ingredients(id) ON DELETE RESTRICT,
  inventory_date DATE NOT NULL,
  opening_quantity NUMERIC(14,3) CHECK (opening_quantity IS NULL OR opening_quantity >= 0),
  closing_quantity NUMERIC(14,3) CHECK (closing_quantity IS NULL OR closing_quantity >= 0),
  opening_note TEXT,
  closing_note TEXT,
  opening_checked_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  closing_checked_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  opening_checked_at TIMESTAMPTZ(6),
  closing_checked_at TIMESTAMPTZ(6),
  CONSTRAINT daily_inventory_ingredient_date_uq UNIQUE (ingredient_id, inventory_date),
  CONSTRAINT daily_inventory_opening_check CHECK (
    (opening_quantity IS NULL AND opening_checked_at IS NULL)
    OR (opening_quantity IS NOT NULL AND opening_checked_at IS NOT NULL)
  ),
  CONSTRAINT daily_inventory_closing_check CHECK (
    (closing_quantity IS NULL AND closing_checked_at IS NULL)
    OR (closing_quantity IS NOT NULL AND closing_checked_at IS NOT NULL)
  )
);
CREATE INDEX daily_inventory_date_idx ON daily_inventory_records(inventory_date);
CREATE TABLE payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE RESTRICT,
  amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
  payment_method VARCHAR(40) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PAID' CHECK (status IN ('PAID','VOIDED','REFUNDED')),
  transaction_ref VARCHAR(120),
  paid_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  recorded_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT
);
CREATE INDEX payments_paid_at_idx ON payments(paid_at DESC);
